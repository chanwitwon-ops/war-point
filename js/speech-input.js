// ─────────────────────────────────────────────────────────────
// js/speech-input.js — ปุ่มไมค์ "พูดแทนพิมพ์" (สเปก 01 หัวข้อ ฉ. ข้อ 7 · เพิ่ม 2026-11-10)
// ใช้ Web Speech API ของเบราว์เซอร์ (ฟรี ไม่ผ่าน AI proxy) แปลงเสียงพูดภาษาไทยเป็นตัวอักษร
// ใช้ได้แน่นอนเฉพาะ Chrome/Edge · ต้องมีเน็ต · ครูต้องกดอนุญาตไมค์
// เบราว์เซอร์ที่ไม่รองรับ → ซ่อนปุ่ม ครูยังพิมพ์ได้ปกติ
//
// วิธีใช้: window.ติดปุ่มไมค์(ช่องข้อความ, ปุ่ม, กล่องสถานะ)
//   ทำเป็นตัวกลางไว้ เผื่อเอาไปใส่ช่องข้อความอื่นภายหลัง (รอบนี้ใช้เฉพาะช่องคำสั่งงาน)
// ─────────────────────────────────────────────────────────────

(function () {
  var ตัวแปลงเสียง = window.SpeechRecognition || window.webkitSpeechRecognition;

  var ข้อความผิดพลาด = {
    "not-allowed": "เบราว์เซอร์ยังไม่ได้รับอนุญาตให้ใช้ไมค์ — กดอนุญาตไมค์ที่แถบที่อยู่เว็บ แล้วลองใหม่",
    "service-not-allowed": "เบราว์เซอร์นี้ไม่อนุญาตให้แปลงเสียง — ลองใช้ Chrome หรือ Edge",
    "no-speech": "ไม่ได้ยินเสียงพูด — กดปุ่มไมค์แล้วพูดใหม่อีกครั้ง",
    "audio-capture": "ไม่พบไมค์ในเครื่อง — ตรวจว่าเสียบไมค์หรือเปิดไมค์อยู่",
    "network": "เชื่อมต่อบริการแปลงเสียงไม่ได้ — ตรวจอินเทอร์เน็ตแล้วลองใหม่"
  };

  window.ติดปุ่มไมค์ = function (ช่อง, ปุ่ม, กล่องสถานะ) {
    if (!ช่อง || !ปุ่ม) return;
    if (!ตัวแปลงเสียง) {
      ปุ่ม.classList.add("hidden");
      return;
    }
    ปุ่ม.classList.remove("hidden");

    var ตัวฟัง = null;
    var กำลังฟัง = false;
    var มีข้อผิดพลาด = false;

    function ตั้งปุ่ม() {
      ปุ่ม.textContent = กำลังฟัง ? "⏹ หยุดฟัง" : "🎤 พูดแทนพิมพ์";
      ปุ่ม.setAttribute("aria-pressed", กำลังฟัง ? "true" : "false");
    }

    function สถานะ(ข้อความ, เป็นข้อผิดพลาด) {
      if (!กล่องสถานะ) return;
      กล่องสถานะ.textContent = ข้อความ || "";
      กล่องสถานะ.classList.toggle("hidden", !ข้อความ);
      กล่องสถานะ.classList.toggle("alert-error", !!เป็นข้อผิดพลาด);
      กล่องสถานะ.classList.toggle("alert-ai", !เป็นข้อผิดพลาด);
    }

    ตั้งปุ่ม();

    ปุ่ม.addEventListener("click", function () {
      if (กำลังฟัง && ตัวฟัง) {
        ตัวฟัง.stop();
        return;
      }

      ตัวฟัง = new ตัวแปลงเสียง();
      ตัวฟัง.lang = "th-TH";
      ตัวฟัง.continuous = true;
      ตัวฟัง.interimResults = true;

      // ข้อความที่พูดจะต่อท้ายของเดิม — ครูพิมพ์ครึ่งหนึ่งแล้วพูดต่อได้
      var ข้อความก่อนพูด = ช่อง.value;
      var ตัวคั่น = ข้อความก่อนพูด && !/\s$/.test(ข้อความก่อนพูด) ? " " : "";
      var ยาวสูงสุด = ช่อง.maxLength > 0 ? ช่อง.maxLength : Infinity;
      มีข้อผิดพลาด = false;

      ตัวฟัง.onresult = function (e) {
        var ที่ได้ = [];
        for (var i = 0; i < e.results.length; i++) {
          ที่ได้.push(e.results[i][0].transcript.trim());
        }
        var ใหม่ = ข้อความก่อนพูด + ตัวคั่น + ที่ได้.filter(Boolean).join(" ");
        if (ใหม่.length > ยาวสูงสุด) {
          ใหม่ = ใหม่.slice(0, ยาวสูงสุด);
          สถานะ("ข้อความยาวถึงขีดจำกัดแล้ว — ส่วนที่เกินไม่ถูกใส่", true);
          มีข้อผิดพลาด = true;
        }
        ช่อง.value = ใหม่;
        ช่อง.dispatchEvent(new Event("input", { bubbles: true }));
      };

      ตัวฟัง.onerror = function (e) {
        if (e.error === "aborted") return;
        มีข้อผิดพลาด = true;
        สถานะ("⚠️ " + (ข้อความผิดพลาด[e.error] || "แปลงเสียงไม่สำเร็จ (" + e.error + ") — พิมพ์แทนได้"), true);
      };

      ตัวฟัง.onend = function () {
        กำลังฟัง = false;
        ตั้งปุ่ม();
        if (!มีข้อผิดพลาด) สถานะ("✅ แปลงเสียงเสร็จแล้ว — ตรวจและแก้ข้อความได้ก่อนบันทึก", false);
      };

      try {
        ตัวฟัง.start();
        กำลังฟัง = true;
        ตั้งปุ่ม();
        สถานะ("🎤 กำลังฟัง… พูดได้เลย แล้วกด \"หยุดฟัง\" เมื่อพูดจบ", false);
      } catch (err) {
        สถานะ("⚠️ เริ่มฟังไม่สำเร็จ: " + err.message + " — พิมพ์แทนได้", true);
      }
    });
  };
})();
